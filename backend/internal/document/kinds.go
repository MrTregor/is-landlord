// Variables — переменные вида: общие и свои (09 разд. 4).
func Variables(kind string) []Variable {
	groups := [][]Variable{commonVars}
	switch kind {
	case KindContractCh35, KindContractCh34:
		groups = append(groups, contractVars)
	case KindActHandover, KindActReturn:
		groups = append(groups, contractVars, actVars)
	case KindAmendment:
		groups = append(groups, contractVars, amendmentVars)
	case KindReceipt:
		groups = append(groups, contractVars, receiptVars)
	case KindRecon:
		groups = append(groups, contractVars, reconVars)
	case KindPdnConsent:
		groups = append(groups, consentVars)
	}
	var out []Variable
	seen := map[string]bool{}
	for _, g := range groups {
		for _, v := range g {
			if !seen[v.Key] {
				seen[v.Key] = true
				out = append(out, v)
			}
		}
	}
	return out
}

// Allowed — допустимые ключи вида (проверка при сохранении шаблона).
func Allowed(kind string) map[string]bool {
	out := map[string]bool{}
	for _, v := range Variables(kind) {
		out[v.Key] = true
	}
	return out
}

// IsKind — известный вид документа.
func IsKind(kind string) bool {
	for _, k := range Kinds {
		if k == kind {
			return true
		}
	}
	return false
}

