// Обязательные примеры 09 Документы и шаблоны разд. 4.6 (16 Тестирование разд. 2 «Деньги»), FR-04.1.
func TestToWordsRu_FR04_1(t *testing.T) {
	cases := []struct {
		kop  Kop
		want string
	}{
		{2_800_000, "двадцать восемь тысяч рублей 00 копеек"},
		{150_325, "одна тысяча пятьсот три рубля 25 копеек"},
		{2_100, "двадцать один рубль 00 копеек"},
		{200_000_000, "два миллиона рублей 00 копеек"},
		{1, "ноль рублей 01 копейка"},
		{112, "один рубль 12 копеек"},
		// Дополнительно: склонения и разряды.
		{2_940_000, "двадцать девять тысяч четыреста рублей 00 копеек"},
		{1_100_022, "одиннадцать тысяч рублей 22 копейки"},
		{21_200_000_00, "двадцать один миллион двести тысяч рублей 00 копеек"},
		{100_000_000_000, "один миллиард рублей 00 копеек"},
		{1_411, "четырнадцать рублей 11 копеек"},
		{-50_00, "минус пятьдесят рублей 00 копеек"},
	}
	for _, c := range cases {
		assert.Equal(t, c.want, ToWordsRu(c.kop), c.kop)
	}
}

func TestPlural(t *testing.T) {
	for n, want := range map[int64]string{0: "дней", 1: "день", 2: "дня", 5: "дней", 11: "дней", 14: "дней", 21: "день", 22: "дня", 111: "дней", 101: "день"} {
		assert.Equal(t, want, Plural(n, "день", "дня", "дней"), n)
	}
}
