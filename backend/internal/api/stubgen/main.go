// Команда stubgen генерирует internal/api/stubs.gen.go: тип StrictUnimplemented, реализующий
// StrictServerInterface так, что каждый метод возвращает 501 «Метод ещё не реализован».
// Сервер встраивает его, а реализованные методы модулей перекрывают заглушки.
// Запускается из make gen-api после oapi-codegen; результат не правится руками.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"sort"
)

func main() {
	if len(os.Args) != 3 {
		log.Fatal("использование: stubgen <api.gen.go> <stubs.gen.go>")
	}
	src, dst := os.Args[1], os.Args[2]

	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, src, nil, parser.SkipObjectResolution)
	if err != nil {
		log.Fatalf("разбор %s: %v", src, err)
	}

	var methods []string
	ast.Inspect(file, func(n ast.Node) bool {
		ts, ok := n.(*ast.TypeSpec)
		if !ok || ts.Name.Name != "StrictServerInterface" {
			return true
		}
		iface, ok := ts.Type.(*ast.InterfaceType)
		if !ok {
			log.Fatal("StrictServerInterface не является интерфейсом")
		}
		for _, m := range iface.Methods.List {
			for _, name := range m.Names {
				methods = append(methods, name.Name)
			}
		}
		return false
	})
	if len(methods) == 0 {
		log.Fatal("StrictServerInterface не найден")
	}
	sort.Strings(methods)

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/api/stubgen. DO NOT EDIT.\n\n")
	b.WriteString("package api\n\n")
	b.WriteString("import (\n\t\"context\"\n\n\t\"landlord/backend/internal/platform/apperr\"\n)\n\n")
	b.WriteString("// StrictUnimplemented — заглушки всех методов API: ответ 501 «Метод ещё не реализован».\n")
	b.WriteString("type StrictUnimplemented struct{}\n\n")
	b.WriteString("var _ StrictServerInterface = StrictUnimplemented{}\n")
	for _, m := range methods {
		fmt.Fprintf(&b, "\nfunc (StrictUnimplemented) %[1]s(context.Context, %[1]sRequestObject) (%[1]sResponseObject, error) {\n\treturn nil, apperr.NotImplemented()\n}\n", m)
	}

	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("форматирование: %v", err)
	}
	if err := os.WriteFile(dst, out, 0o644); err != nil {
		log.Fatal(err)
	}
}
